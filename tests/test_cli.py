import json

from logic_agent.cli import main


def test_global_options_after_subcommand(tmp_path, capsys):
    code = main(["devices", "--backend", "mock", "--data-dir", str(tmp_path)])
    assert code == 0
    payload = json.loads(capsys.readouterr().out)
    assert payload["backend"] == "mock"
    assert payload["devices"][0]["id"] == "mock-0"


def test_capture_command_reports_capture_id(tmp_path, capsys):
    code = main(
        [
            "capture",
            "--channels", "D0",
            "--sample-rate", "1000000",
            "--duration", "0.005",
            "--backend", "mock",
            "--data-dir", str(tmp_path),
        ]
    )
    assert code == 0
    payload = json.loads(capsys.readouterr().out)
    assert payload["ok"] is True
    assert payload["capture_id"]


def test_view_exports_vcd_with_channels_and_timestamps(tmp_path, capsys):
    from logic_agent.cli import main

    assert main(
        [
            "capture",
            "--channels", "D0,D1",
            "--sample-rate", "1000000",
            "--duration", "0.000064",
            "--backend", "mock",
            "--data-dir", str(tmp_path / "data"),
        ]
    ) == 0
    captured = json.loads(capsys.readouterr().out)
    output = tmp_path / "wave.vcd"
    assert main(
        [
            "view",
            captured["capture_id"],
            "--output", str(output),
            "--no-open",
            "--data-dir", str(tmp_path / "data"),
        ]
    ) == 0
    payload = json.loads(capsys.readouterr().out)
    assert payload["ok"] is True
    assert payload["launched"] is False
    assert payload["channels"] == ["D0", "D1"]
    text = output.read_text(encoding="utf-8")
    assert "$timescale 1ns $end" in text
    assert "$var wire 1 ! D0 $end" in text
    assert "$var wire 1 \" D1 $end" in text
    assert "#0" in text



def test_decode_command_reports_protocol_events(tmp_path, capsys):
    from logic_agent.decoders import DecoderRuntime
    from logic_agent.service import LogicAgentService

    if DecoderRuntime.discover() is None:
        import pytest

        pytest.skip("sigrok-cli decoder runtime is not installed")

    service = LogicAgentService(data_dir=tmp_path / "seed")
    from tests.test_decoders import _i2c_bytes

    csv = tmp_path / "i2c.csv"
    channels = _i2c_bytes(0x50, 0x4B)
    lines = ["; CSV, generated by test", "; Sample rate: 1000000", "Time(s),SCL,SDA"]
    for index in range(len(channels["SCL"])):
        lines.append(
            f"{index / 1_000_000:.9f},{channels['SCL'][index]},{channels['SDA'][index]}"
        )
    csv.write_text("\n".join(lines) + "\n", encoding="utf-8")
    imported = service.import_csv({"path": str(csv), "channels": ["SCL", "SDA"]})

    code = main(
        [
            "decode",
            imported["capture_id"],
            "i2c",
            "--channels", "scl=SCL,sda=SDA",
            "--max-events", "10",
            "--data-dir", str(tmp_path / "seed"),
        ]
    )
    assert code == 0
    payload = json.loads(capsys.readouterr().out)
    assert payload["event_count"] >= 1
    assert payload["protocol"] == "i2c"
